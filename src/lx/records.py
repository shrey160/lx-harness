"""Synthetic noisy-order normalization domain and independent verifier.

Inputs are deliberately text-only. Dev and held-out records use disjoint
rendering templates and independently seeded generators. Controller truth is
written outside the worker input directory and never copied into its manifest.
"""

from __future__ import annotations

import json
import random
import re
from dataclasses import dataclass
from datetime import date, timedelta
from pathlib import Path
from typing import Mapping


MAX_SPLIT_COUNT = 1000
FIELDS = ("order_id", "customer", "date", "currency", "amount_minor", "phone", "tags")
_CURRENCIES = ("USD", "INR", "EUR")
_ENGLISH_MONTHS = (
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December",
)
_NAMES = (
    "Mira Solis", "Theo Wren", "Asha Bell", "Niko Vale", "Lena Moss",
    "Omar Finch", "Rhea Quinn", "Ivo Reed", "Zara North", "Emil Lake",
    "Talia Fox", "Arun Snow", "Cleo Hart", "Dev Rowan", "Sana Pike",
    "Remy Stone", "Nia Frost", "Ezra Bloom", "Kavi Dawn", "Iris Cove",
)
_TAG_POOL = ("gift", "priority", "fragile", "subscription", "backorder", "wholesale")
_PHONE_NULL_RATE = 0.22

# Each split has a separate bank of sentence structures. Keep these banks
# disjoint: held-out wording should not be learned from development examples.
_DEV_RENDERERS = (
    "Order {order_id} | buyer={customer} | placed {date} | total {amount} | phone {phone} | labels {tags}.",
    "Please process {order_id}. Customer: {customer}. Date of order: {date}. Charge {amount}. Contact: {phone}. Notes: {tags}.",
    "[{order_id}] {customer} ordered on {date}; payment was {amount}. Reach them at {phone}. Categories: {tags}.",
    "Ref {order_id}\nName -> {customer}\nPurchase date -> {date}\nPaid -> {amount}\nTel -> {phone}\nFlags -> {tags}",
)
_HELDOUT_RENDERERS = (
    "Fulfillment slip #{order_id}: account holder {customer}; submitted {date}; collected {amount}; callback {phone}; markers {tags}.",
    "Record {order_id} — {date} / {customer} / gross {amount} / dial {phone} / keywords {tags}.",
    "Ship request {order_id}. Buyer name is {customer}; the purchase day is {date}; tender {amount}; ring {phone}; labels={tags}.",
    "<{order_id}>\nClient :: {customer}\nBooked :: {date}\nValue :: {amount}\nNumber :: {phone}\nKeywords :: {tags}",
)


@dataclass(frozen=True)
class RecordsDataset:
    """Generated dataset paths and in-memory inputs/truth."""

    root: Path
    worker_inputs: tuple[Mapping[str, str], ...]
    controller_truth: Mapping[str, Mapping[str, object]]


@dataclass(frozen=True)
class RecordVerificationResult:
    accepted: bool
    errors: tuple[str, ...]
    score: float
    n_passed: int
    n_criteria: int


def _split_rng(seed: int, split: str) -> random.Random:
    # A fixed split-specific offset avoids Python's process-randomized hash().
    return random.Random(seed + (0x51A7 if split == "dev" else 0xA11D))


def _amount(rng: random.Random) -> tuple[str, int]:
    minor = rng.randint(125, 987654)
    major, fraction = divmod(minor, 100)
    return f"{major:,}.{fraction:02d}", minor


def _date_text(rng: random.Random) -> tuple[str, str]:
    day = date(2021, 1, 1) + timedelta(days=rng.randrange(365 * 6))
    # Spell the month from a fixed English table instead of locale-sensitive
    # strftime directives, keeping generated bytes stable across machines.
    return f"{day.day:02d} {_ENGLISH_MONTHS[day.month - 1]} {day.year:04d}", day.isoformat()


def _phone(rng: random.Random, phone_index: int) -> tuple[str | None, str]:
    if rng.random() < _PHONE_NULL_RATE:
        return None, "not provided"
    # 202-555-0100 through 202-555-0199 are reserved fictional NANP numbers.
    e164 = f"+1202555{100 + phone_index % 100:04d}"
    digits = e164[-10:]
    renderings = (
        f"+1 ({digits[:3]}) {digits[3:6]}-{digits[6:]}",
        f"{digits[:3]}.{digits[3:6]}.{digits[6:]}",
        f"+1-{digits[:3]}-{digits[3:6]}-{digits[6:]}",
    )
    return e164, rng.choice(renderings)


def _make_record(rng: random.Random, index: int, split: str) -> tuple[dict[str, str], dict[str, object]]:
    sample_id = f"{split}-order-{index + 1:04d}"
    source_id = f"{split}-source-{index + 1:04d}"
    order_id = f"LX-{rng.randrange(10, 100):02d}{rng.randrange(100000, 1000000)}"
    customer = _NAMES[rng.randrange(len(_NAMES))]
    noisy_customer = rng.choice((customer.upper(), f"  {customer.lower()} ", customer.replace(" ", "   ")))
    date_input, order_date = _date_text(rng)
    currency = rng.choice(_CURRENCIES)
    amount_display, amount_minor = _amount(rng)
    phone_index = index + (0 if split == "dev" else 47)
    phone, phone_input = _phone(rng, phone_index)

    # Include at least one tag, with occasional duplicate/case noise to make
    # canonicalization observable without making the intended tags ambiguous.
    selected = rng.sample(_TAG_POOL, k=rng.randint(1, 3))
    canonical_tags = sorted(set(selected))
    noisy_tags = [tag.upper() if rng.randrange(2) else tag.title() for tag in selected]
    if rng.randrange(3) == 0:
        noisy_tags.append(noisy_tags[0].lower())
    rng.shuffle(noisy_tags)

    renderer_bank = _DEV_RENDERERS if split == "dev" else _HELDOUT_RENDERERS
    rendered = renderer_bank[index % len(renderer_bank)].format(
        order_id=order_id,
        customer=noisy_customer,
        date=date_input,
        amount=f"{currency} {amount_display}",
        phone=phone_input,
        tags=" / ".join(noisy_tags),
    )
    worker_record = {
        "sample_id": sample_id,
        "source_id": source_id,
        "split": split,
        "text": rendered,
    }
    truth: dict[str, object] = {
        "order_id": order_id,
        "customer": customer,
        "date": order_date,
        "currency": currency,
        "amount_minor": amount_minor,
        "phone": phone,
        "tags": canonical_tags,
    }
    return worker_record, truth


def build_records_dataset(
    root: str | Path,
    dev_count: int = 20,
    heldout_count: int = 40,
    seed: int = 20261028,
) -> RecordsDataset:
    """Build deterministic dev/held-out order samples and separated truth.

    Counts are independently bounded to 0..1000. The same seed and counts
    produce byte-for-byte identical JSON files. Split source IDs, random
    streams, and rendering templates are disjoint.
    """
    for label, count in (("dev_count", dev_count), ("heldout_count", heldout_count)):
        if type(count) is not int or not 0 <= count <= MAX_SPLIT_COUNT:
            raise ValueError(f"{label} must be an integer from 0 to {MAX_SPLIT_COUNT}")
    if type(seed) is not int:
        raise ValueError("seed must be an integer")

    root = Path(root)
    worker_dir = root / "worker_inputs"
    truth_dir = root / "controller_truth"
    worker_dir.mkdir(parents=True, exist_ok=True)
    truth_dir.mkdir(parents=True, exist_ok=True)

    inputs: list[dict[str, str]] = []
    truth: dict[str, dict[str, object]] = {}
    for split, count in (("dev", dev_count), ("heldout", heldout_count)):
        rng = _split_rng(seed, split)
        for index in range(count):
            worker_record, expected = _make_record(rng, index, split)
            inputs.append(worker_record)
            truth[worker_record["sample_id"]] = expected

    manifest = {"samples": inputs}
    (worker_dir / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    (truth_dir / "ground_truth.json").write_text(
        json.dumps(truth, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return RecordsDataset(
        root=root,
        worker_inputs=tuple(inputs),
        controller_truth=truth,
    )


def _field_is_well_typed(field: str, value: object) -> bool:
    if field in ("order_id", "customer", "date", "currency"):
        return type(value) is str
    if field == "amount_minor":
        return type(value) is int  # bool is intentionally rejected
    if field == "phone":
        return value is None or type(value) is str
    if field == "tags":
        return (
            type(value) is list
            and all(type(tag) is str for tag in value)
            and value == sorted(set(value))
            and all(tag == tag.lower() for tag in value)
        )
    return False


def _valid_date(value: object) -> bool:
    if type(value) is not str or re.fullmatch(r"\d{4}-\d{2}-\d{2}", value) is None:
        return False
    try:
        return date.fromisoformat(value).isoformat() == value
    except ValueError:
        return False


def verify_record(expected: Mapping[str, object], candidate: object) -> RecordVerificationResult:
    """Score a normalized order by field, with strict schema/type validation.

    Error feedback names the field and contract issue only; it never includes
    expected values. Unknown fields increase the criteria denominator and
    prevent acceptance. Score is exactly ``n_passed / n_criteria``.
    """
    if type(candidate) is not dict:
        return RecordVerificationResult(False, ("output must be a JSON object",), 0.0, 0, len(FIELDS))

    errors: list[str] = []
    expected_keys = set(FIELDS)
    candidate_keys = set(candidate)
    missing = expected_keys - candidate_keys
    extra = candidate_keys - expected_keys
    for field in sorted(missing):
        errors.append(f"{field}: required field is missing")
    for field in sorted(extra, key=lambda item: str(item)):
        errors.append(f"schema: unknown field {field!r}")

    correct = 0
    for field in FIELDS:
        if field not in candidate:
            continue
        value = candidate[field]
        if not _field_is_well_typed(field, value):
            if field == "date":
                errors.append("date: must be a valid YYYY-MM-DD string")
            elif field == "amount_minor":
                errors.append("amount_minor: must be an integer (not a boolean)")
            elif field == "phone":
                errors.append("phone: must be an E.164 string or null")
            elif field == "tags":
                errors.append("tags: must be unique, sorted, lowercase strings")
            else:
                errors.append(f"{field}: must be a string")
            continue
        if field == "date" and not _valid_date(value):
            errors.append("date: must be a valid YYYY-MM-DD date")
            continue
        if field == "phone" and value is not None and re.fullmatch(r"\+[1-9]\d{7,14}", value) is None:
            errors.append("phone: must use E.164 format or null")
            continue
        if field in expected and value == expected[field]:
            correct += 1
        else:
            errors.append(f"{field}: value does not match")

    n_criteria = len(FIELDS) + len(extra)
    score = correct / n_criteria
    accepted = not errors
    return RecordVerificationResult(accepted, tuple(errors), score, correct, n_criteria)
